var quarterFolders = []string{"1T", "2T", "3T", "4T", "Anual", "Sin periodo"}

var kindFolders = []struct {
	Kind   string
	Folder string
}{
	{"factura_emitida", "Facturas emitidas"},
	{"factura_recibida", "Facturas recibidas"},
	{"factura", "Facturas"},
	{"nomina", "Nóminas"},
	{"justificante", "Justificantes"},
	{"modelo", "Modelos"},
	{"recibo", "Recibos"},
	{"contrato", "Contratos"},
	{"seguro", "Seguros"},
	{"banco", "Banco"},
	{"other", "Otros"},
}

var kindByFolder = func() map[string]string {
	m := map[string]string{}
	for _, it := range kindFolders {
		m[strings.ToLower(it.Folder)] = it.Kind
	}
	return m
}()

func KindFolder(kind string) string {
	for _, it := range kindFolders {
		if it.Kind == kind {
			return it.Folder
		}
	}
	return "Otros"
}

func KindFromFolder(name string) string {
	return kindByFolder[strings.ToLower(strings.TrimSpace(name))]
}

// Years returns the tree years generated by default.
func Years() []int {
	now := time.Now().Year()
	return []int{now - 1, now, now + 1}
}

type TreeResult struct {
	Root      string `json:"root"`
	Taxpayers int    `json:"taxpayers"`
	Folders   int    `json:"folders"`
}

// EnsureTree creates the complete directory tree for every taxpayer. It is
// idempotent and can be run whenever a taxpayer is added or the root changes.
func (s *Service) EnsureTree(ctx context.Context) (TreeResult, error) {
	root, err := s.Root(ctx)
	if err != nil {
		return TreeResult{}, err
	}
	res := TreeResult{Root: root}
	if root == "" {
		return res, nil
	}
	taxpayers, err := s.Store.ListTaxpayers(ctx)
	if err != nil {
		return res, err
	}
	for _, t := range taxpayers {
		n, err := EnsureTaxpayerTree(root, t, Years())
		if err != nil {
			return res, fmt.Errorf("%s: %w", t.Name, err)
		}
		res.Folders += n
	}
	// Documents that cannot be assigned to any taxpayer live here until the
	// review queue resolves them.
	unclassified := filepath.Join(root, "Sin clasificar")
	if _, err := os.Stat(unclassified); os.IsNotExist(err) {
		if err := os.MkdirAll(unclassified, 0o750); err != nil {
			return res, fmt.Errorf("crear %s: %w", unclassified, err)
		}
		res.Folders++
	}
	res.Taxpayers = len(taxpayers)
	return res, nil
}

// EnsureTaxpayerTree creates <root>/<entity>/<year>/<period>/<kind>.
func EnsureTaxpayerTree(root string, t domain.Taxpayer, years []int) (int, error) {
	// Reuse an existing <name> (NIF) folder so renaming a taxpayer does not
	// split its documents into a second tree.
	base := filepath.Join(root, ExistingFolder(root, t))
	created := 0
	dirs := []string{base, filepath.Join(base, "Sin clasificar")}
	for _, year := range years {
		for _, period := range quarterFolders {
			for _, kind := range kindFolders {
				dirs = append(dirs, filepath.Join(base, strconv.Itoa(year), period, kind.Folder))
			}
		}
	}
	for _, dir := range dirs {
		if _, err := os.Stat(dir); err == nil {
			continue
		}
		if err := os.MkdirAll(dir, 0o750); err != nil {
			return created, fmt.Errorf("crear %s: %w", dir, err)
		}
		created++
	}
	return created, nil
}

// FolderName is the stable, human-readable top-level folder for a taxpayer.
func FolderName(t domain.Taxpayer) string {
	name := sanitizeSegment(t.Name)
	nif := sanitizeSegment(strings.ToUpper(t.NIF))
	if name == "" {
		name = nif
	}
	if nif != "" {
		return fmt.Sprintf("%s (%s)", name, nif)
	}
	return name
}

// ExistingFolder returns an existing top-level folder for the taxpayer. This
// keeps documents together if the taxpayer was renamed after the tree existed.
func ExistingFolder(root string, t domain.Taxpayer) string {
	entries, err := os.ReadDir(root)
	if err != nil {
		return FolderName(t)
	}
	suffix := "(" + strings.ToUpper(t.NIF) + ")"
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		if strings.HasSuffix(strings.ToUpper(e.Name()), suffix) {
			return e.Name()
		}
	}
	return FolderName(t)
}

func sanitizeSegment(value string) string {
	value = strings.TrimSpace(value)
	if value == "" {
		return ""
	}
	var b strings.Builder
	lastSpace := false
	for _, r := range value {
		invalid := r == '/' || r == '\\' || r == ':' || r == '*' || r == '?' ||
			r == '"' || r == '<' || r == '>' || r == '|' || unicode.IsControl(r)
		if invalid {
			r = '-'
		}
		if unicode.IsSpace(r) {
			if lastSpace {
				continue
			}
			r = ' '
			lastSpace = true
		} else {
			lastSpace = false
		}
		b.WriteRune(r)
	}
	out := strings.Trim(b.String(), " .-")
	if len([]rune(out)) > 90 {
		out = string([]rune(out)[:90])
		out = strings.Trim(out, " .-")
	}
	return out
}

// SanitizeFilename keeps the original name but removes path separators and
// control characters.
func SanitizeFilename(name string) string {
	name = filepath.Base(strings.TrimSpace(name))
	name = sanitizeSegment(name)
	if name == "" || name == "." {
		return "documento"
	}
	return name
}

// PeriodFromDate returns the tree year and quarter folder for a date.
func PeriodFromDate(date string) (int, string) {
	parsed, err := time.Parse("2006-01-02", strings.TrimSpace(date))
	if err != nil {
		return 0, ""
	}
	return parsed.Year(), QuarterFolder(parsed.Month())
}

func QuarterFolder(month time.Month) string {
	switch {
	case month >= time.January && month <= time.March:
		return "1T"
	case month >= time.April && month <= time.June:
		return "2T"
	case month >= time.July && month <= time.September:
		return "3T"
	default:
		return "4T"
	}
}

// Destination returns the relative path for a classified document.
func Destination(root string, t domain.Taxpayer, year int, period, kind, filename string) string {
	folder := ExistingFolder(root, t)
	if year == 0 {
		year = time.Now().Year()
	}
	if period == "" {
		period = "Sin periodo"
	}
	return filepath.Join(folder, strconv.Itoa(year), period, KindFolder(kind), SanitizeFilename(filename))
}

// UniquePath appends a counter when a different file already occupies the
// desired path.
func UniquePath(abs string, sha string) (string, error) {
	if _, err := os.Stat(abs); os.IsNotExist(err) {
		return abs, nil
	}
	existing, err := sha256File(abs)
	if err == nil && existing == sha {
		return abs, nil
	}
	ext := filepath.Ext(abs)
	base := strings.TrimSuffix(abs, ext)
	for i := 2; i < 1000; i++ {
		candidate := fmt.Sprintf("%s (%d)%s", base, i, ext)
		if _, err := os.Stat(candidate); os.IsNotExist(err) {
			return candidate, nil
		}
	}
	return "", fmt.Errorf("no se encontró un nombre libre para %s", filepath.Base(abs))
}
